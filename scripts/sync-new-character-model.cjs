const fs = require('node:fs');
const path = require('node:path');
const {createNewCharacterModels} = require('./new-character-model.cjs');
const root = path.resolve(__dirname, '..');
const file = path.join(root, 'js/base.js');
let source = fs.readFileSync(file,'utf8');
const start = '// BEGIN GENERATED NEW CHARACTER MODELS';
const end = '// END GENERATED NEW CHARACTER MODELS';
const block = `${start}\n// Generated by scripts/sync-new-character-model.cjs; edit the source model.\nconst newCharacterModels = (${createNewCharacterModels.toString()})();\nnewCharacterModels.install(roleList, RoleSumProperty);\n${end}\n`;
// Keep the user-facing role list's C0 literals in sync too, replacing copied placeholders.
const model = createNewCharacterModels();
for (const id of model.ids) {
    const begin = source.indexOf('"id": ' + id + ',');
    const finish = source.indexOf('\n    }', begin);
    if (begin < 0 || finish < begin) throw new Error('Role missing: ' + id);
    let entry = source.slice(begin, finish);
    const {weights} = model.profile({roleListId:id});
    for (const key of ['normal','skill','heavy','liberate','other','maxscore']) {
        entry = entry.replace(new RegExp('("' + key + '":\\s*)[\\d.]+'), '$1' + weights[key]);
    }
    source = source.slice(0, begin) + entry + source.slice(finish);
}
if(source.includes(start)) source=source.slice(0,source.indexOf(start))+block+source.slice(source.indexOf(end)+end.length).replace(/^\r?\n/,'');
else source=source.replace('//计算角色声骸超越人数百分比的分母',block+'//计算角色声骸超越人数百分比的分母');
fs.writeFileSync(file,source);
console.log('Updated embedded character model (57–63).');
